function bildCards(): ExplainCard[] {
  return Object.entries(BILD).flatMap(([kind, list]) =>
    list.map((entry) => {
      const i = entry.indexOf(' ')
      return {
        level: 'bild' as const,
        kind,
        emoji: entry.slice(0, i),
        word: entry.slice(i + 1),
      }
    }),
  )
}

function wortCards(): ExplainCard[] {
  return Object.entries(WORT).flatMap(([kind, list]) =>
    list.map((word) => ({ level: 'wort' as const, kind, word })),
  )
}

export const EXPLAIN: Readonly<Record<ExplainLevel, readonly ExplainCard[]>> = {
  bild: bildCards(),
  wort: wortCards(),
}
